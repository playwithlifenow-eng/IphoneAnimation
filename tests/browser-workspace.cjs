const assert = require("node:assert/strict");
exports.run = async ({ page, state, doc, check }) => {
  const choose = async id => page.evaluate(async id => (await import("/src/store.ts")).studio.select([id]), id);
  const drag = async (locator, dx, dy = 0, cancel = false) => {
    const b = await locator.boundingBox();
    await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2);
    await page.mouse.down();
    await page.mouse.move(b.x + b.width / 2 + dx, b.y + b.height / 2 + dy, { steps: 8 });
    if (cancel) await page.keyboard.press("Escape");
    await page.mouse.up();
  };
  await page.waitForFunction(() => document.querySelectorAll(".scene-view > .scene-status").length === 0, {}, { timeout: 45000 });
  await page.setViewportSize({ width: 1366, height: 768 });
  assert.equal(await page.locator(".topbar").evaluate(e => Math.round(e.getBoundingClientRect().height)), 44);
  assert(await page.locator(".topbar").evaluate(e => e.scrollWidth <= e.clientWidth));
  const canvasBefore = (await page.locator(".canvas-board").boundingBox()).height;
  await page.getByLabel("Collapse choreography", { exact: true }).click();
  assert((await page.locator(".canvas-board").boundingBox()).height > canvasBefore + 100);
  await page.getByLabel("Fit composition", { exact: true }).click();
  await page.screenshot({ path: "test-results/workspace-laptop.png" });
  await page.getByLabel("Toggle layers panel", { exact: true }).click();
  await page.getByLabel("Toggle inspector panel", { exact: true }).click();
  assert.equal(await page.locator(".left-panel").isVisible(), false);
  assert.equal(await page.locator(".right-panel").isVisible(), false);
  assert((await page.locator(".canvas-board").boundingBox()).width > 1350);
  await page.reload(); await page.waitForLoadState("networkidle");
  assert.equal(await page.locator(".left-panel").isVisible(), false);
  assert.equal(await page.locator(".right-panel").isVisible(), false);
  assert.equal(await page.getByLabel("Expand choreography", { exact: true }).count(), 1);
  await page.getByLabel("Toggle layers panel", { exact: true }).click();
  await page.getByLabel("Toggle inspector panel", { exact: true }).click();
  const width = (await page.locator(".left-panel").boundingBox()).width;
  await drag(page.getByRole("separator", { name: "Resize layers panel" }), 30);
  assert(Math.abs((await page.locator(".left-panel").boundingBox()).width - width - 30) < 2);
  await page.getByRole("separator", { name: "Resize layers panel" }).press("ArrowLeft");
  assert(Math.abs((await page.locator(".left-panel").boundingBox()).width - width - 20) < 2);
  await drag(page.getByRole("separator", { name: "Resize layers panel" }), -20);
  await page.getByLabel("Expand choreography", { exact: true }).click();
  const timelineHeight = (await page.locator(".tl-panel").boundingBox()).height;
  await drag(page.getByRole("separator", { name: "Resize choreography" }), 0, -35);
  assert(Math.abs((await page.locator(".tl-panel").boundingBox()).height - timelineHeight - 35) < 2);
  await drag(page.getByRole("separator", { name: "Resize choreography" }), 0, 35);
  check("1366×768 compact header, panel collapse persistence and pointer/keyboard panel resizing");

  await choose("headline");
  const original = (await doc()).entities.find(e => e.id === "headline").props.x;
  const revision = (await doc()).revision;
  await drag(page.getByLabel("Scrub X", { exact: true }), 24);
  assert.equal((await doc()).entities.find(e => e.id === "headline").props.x, original + 24);
  assert.equal((await doc()).revision, revision + 1);
  await page.getByLabel("Undo", { exact: true }).click();
  assert.equal((await doc()).entities.find(e => e.id === "headline").props.x, original);
  const cancelRevision = (await doc()).revision;
  await drag(page.getByLabel("Scrub X", { exact: true }), 35, 0, true);
  assert.equal((await doc()).entities.find(e => e.id === "headline").props.x, original);
  assert.equal((await doc()).revision, cancelRevision);
  check("Numeric scrubbing is live, one undoable change, and cancellable with Escape");

  await choose("phone");
  await page.getByLabel("Responsive profile", { exact: true }).selectOption("mobile");
  const base = (await doc()).tracks.find(t => t.entityId === "phone" && t.property === "rotateY" && t.profileId === "base");
  await page.getByLabel("Scrub Rotate Y", { exact: true }).scrollIntoViewIfNeeded();
  await drag(page.getByLabel("Scrub Rotate Y", { exact: true }), 18);
  assert.deepEqual((await doc()).tracks.find(t => t.id === base.id), base);
  const fork = (await doc()).tracks.find(t => t.entityId === "phone" && t.property === "rotateY" && t.profileId === "mobile");
  assert(fork);
  assert.equal(await page.getByLabel("Inherit base Rotate Y", { exact: true }).count(), 1);
  assert.equal(await page.getByLabel("Go to nearest Rotate Y key", { exact: true }).count(), 1);
  await page.getByLabel("Inherit base Rotate Y", { exact: true }).click();
  assert.equal((await doc()).tracks.some(t => t.id === fork.id), false);
  await page.getByLabel("Undo", { exact: true }).click();
  assert.deepEqual((await doc()).tracks.find(t => t.id === fork.id), fork);
  await page.getByLabel("Undo", { exact: true }).click();
  assert.equal((await doc()).tracks.some(t => t.id === fork.id), false);
  await page.getByLabel("Responsive profile", { exact: true }).selectOption("desktop");
  await page.evaluate(async () => (await import("/src/store.ts")).studio.session({ playhead: 2 }));
  await page.getByLabel("Go to nearest Rotate Y key", { exact: true }).click();
  assert.equal((await state()).playhead, 0);
  check("Responsive animation badges coexist; inherit-base is reversible and keys navigate their clock");

  await choose("headline");
  await page.setViewportSize({ width: 1512, height: 982 });
  // Restore original zoom so the existing regression gestures retain their tested viewport.
  await page.evaluate(async () => (await import("/src/store.ts")).studio.session({ zoom: .73 }));
};
