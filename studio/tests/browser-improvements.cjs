const assert = require("node:assert/strict");
exports.editor = async ({ page, state, doc, check }) => {
  const choose = async id => page.evaluate(async id => { const { studio } = await import("/src/store.ts"); studio.select([id]); studio.session({ playing: false }); }, id);
  const drag = async (x, y, dx, dy) => { await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + dx, y + dy, { steps: 5 }); await page.mouse.up(); };
  await page.getByRole("button", { name: "Layers", exact: true }).click();
  await page.getByLabel("Select tool", { exact: true }).click();
  await page.evaluate(async () => { const { studio } = await import("/src/store.ts"); studio.session({ signals: { pointerX: .5, pointerY: .5, scroll: 0 }, playhead: 4, clockId: "page" }); });
  await choose("headline");
  await page.getByRole("tab", { name: "Design", exact: true }).click();
  const before = await doc();
  const headline = await page.locator('[data-entity="headline"]').boundingBox();
  await drag(headline.x + 25, headline.y + 25, 20, 10);
  const after = await doc();
  assert.equal(after.revision, before.revision + 1);
  assert(after.tracks.find(t => t.entityId === "headline" && t.property === "x").keys.find(k => k.time === 4).value > before.tracks.find(t => t.entityId === "headline" && t.property === "x").keys.find(k => k.time === 4).value);
  await page.getByLabel("Undo", { exact: true }).click();
  await page.getByLabel("Animated edit mode").selectOption("offset");
  const oldKeys = (await doc()).tracks.find(t => t.entityId === "headline" && t.property === "x").keys;
  const x = Number(await page.getByLabel("X", { exact: true }).inputValue());
  await page.getByLabel("X", { exact: true }).fill(String(x + 20));
  await page.getByLabel("X", { exact: true }).blur();
  assert.deepEqual((await doc()).tracks.find(t => t.entityId === "headline" && t.property === "x").keys.map(k => k.value), oldKeys.map(k => k.value + 20));
  await page.getByLabel("Undo", { exact: true }).click();
  await page.getByLabel("Animated edit mode").selectOption("key");
  await page.keyboard.press("Escape");
  assert.deepEqual((await state()).selection, []);
  check("Tracked canvas dragging, whole-curve offsets, undo and Escape deselection");

  const sceneSize = await page.locator('[data-entity="phone"]').evaluate(e => ({ frame: e.getBoundingClientRect().width, canvas: e.querySelector("canvas").getBoundingClientRect().width }));
  assert(Math.abs(sceneSize.frame - sceneSize.canvas) < 2, "WebGL viewport must not receive canvas zoom twice");
  // Find a genuinely painted and empty pixel in the actual loaded GLB canvas.
  const pixels = await page.locator('[data-entity="phone"] canvas').evaluate(async canvas => {
    const img = await createImageBitmap(canvas), off = document.createElement("canvas"); off.width = img.width; off.height = img.height;
    const c = off.getContext("2d"); c.drawImage(img, 0, 0); const data = c.getImageData(0, 0, off.width, off.height).data, r = canvas.getBoundingClientRect();
    let hit, miss;
    for (let y = Math.floor(off.height * .15); y < off.height * .85; y += 5) for (let x = Math.floor(off.width * .1); x < off.width * .9; x += 5) {
      const p = { x: r.left + x / off.width * r.width, y: r.top + y / off.height * r.height, localX: x / off.width, localY: y / off.height };
      if (!hit && data[(y * off.width + x) * 4 + 3] > 240) hit = p;
      if (!miss && data[(y * off.width + x) * 4 + 3] === 0) miss = p;
    }
    return { hit, miss };
  });
  assert(pixels.hit && pixels.miss);
  await page.mouse.click(pixels.hit.x, pixels.hit.y);
  assert.deepEqual((await state()).selection, ["phone"]);
  await page.evaluate(async p => {
    const { studio } = await import("/src/store.ts"), { makeEntity } = await import("/src/seed.ts"), { evaluateEntity } = await import("/src/model.ts");
    const s = studio.get(), d = s.workspace.document, phone = d.entities.find(e => e.id === "phone"), v = evaluateEntity(d, phone, s.profileId, s.playhead, s.signals);
    const behind = makeEntity("text"); behind.id = "hit-fixture"; behind.name = "Behind model"; behind.props = { ...behind.props, x: (p.x - document.querySelector(".composition-page").getBoundingClientRect().left) / s.zoom - 12, y: (p.y - document.querySelector(".composition-page").getBoundingClientRect().top) / s.zoom - 12, width: 24, height: 24, text: "•" }; behind.overrides = {};
    studio.execute({ type: "insert", entities: [behind] });
    studio.execute({ type: "reorder", ids: [behind.id, ...d.entities.map(e => e.id)] });
  }, pixels.miss);
  await page.mouse.click(pixels.miss.x, pixels.miss.y);
  assert.deepEqual((await state()).selection, ["hit-fixture"]);
  await page.evaluate(async () => { const { studio } = await import("/src/store.ts"); studio.execute({ type: "remove", ids: ["hit-fixture"] }); });
  await choose("phone");
  await page.mouse.click(pixels.miss.x, pixels.miss.y);
  assert.deepEqual((await state()).selection, []);
  await choose("phone");
  await page.getByLabel("Orbit scene tool", { exact: true }).click();
  await page.getByLabel("Orbit sensitivity").fill("1.5");
  const rotation = (await doc()).tracks.find(t => t.entityId === "phone" && t.property === "rotateY").keys.find(k => k.time === 4).value;
  await drag(pixels.hit.x, pixels.hit.y, 20, 0);
  assert(Math.abs((await doc()).tracks.find(t => t.entityId === "phone" && t.property === "rotateY").keys.find(k => k.time === 4).value - rotation - 30) < .1);
  await page.getByLabel("Undo", { exact: true }).click();
  await page.getByLabel("Select tool", { exact: true }).click();
  check("Real GLB mesh picking, transparent-space pass-through, background deselection and adjustable orbit");

  const heightBefore = await page.locator(".canvas-board").evaluate(e => e.clientHeight);
  await page.getByLabel("Collapse choreography", { exact: true }).click();
  assert((await page.locator(".canvas-board").evaluate(e => e.clientHeight)) > heightBefore);
  await page.getByLabel("Expand choreography", { exact: true }).click();
  await page.getByRole("button", { name: "+ Add section below", exact: true }).click();
  let d = await doc(); const sections = d.entities.filter(e => e.kind === "section");
  assert.equal(sections.length, 2);
  assert.equal(d.entities.find(e => e.id === "phone").parentId, sections[0].id);
  await page.getByLabel("Undo", { exact: true }).click();
  assert.equal((await doc()).entities.filter(e => e.kind === "section").length, 0);
  await page.getByLabel("Redo", { exact: true }).click();
  await choose(sections[0].id);
  await page.getByLabel("Section height mode").selectOption("viewport");
  await page.getByLabel("Pin section", { exact: true }).check();
  await page.getByLabel("Scroll distance", { exact: true }).fill("200");
  await page.getByLabel("Scroll distance", { exact: true }).blur();
  // Seed uses a stable copy ID; identify it by name if a fixture changed.
  d = await doc(); const copy = d.entities.find(e => e.name === "Supporting copy");
  await choose(copy.id);
  await page.getByRole("button", { name: "Motion actions", exact: true }).click();
  await page.getByRole("button", { name: "Apply to 1 element", exact: true }).click();
  d = await doc(); const action = d.actions.at(-1);
  assert(action && action.clockId !== "page");
  await page.getByLabel("Animation playhead", { exact: true }).fill("1");
  assert((await page.locator(".tl-time").innerText()).includes("13%"));
  const values = await page.locator(`[data-entity="${copy.id}"]`).evaluate(e => ({ opacity: Number(getComputedStyle(e).opacity), transform: getComputedStyle(e).transform }));
  assert(Math.abs(values.opacity - .5) < .01);
  await page.getByLabel("Animation playhead", { exact: true }).fill("2");
  assert.equal(await page.locator(`[data-entity="${copy.id}"]`).evaluate(e => Number(getComputedStyle(e).opacity)), 1);
  assert((await state()).signals.scroll > 0);
  const keyLabel = `${copy.name} translateY key at 25%`;
  await page.getByLabel(keyLabel, { exact: true }).click();
  assert.equal(await page.getByLabel("Key time", { exact: true }).inputValue(), "25");
  await page.getByLabel("Choreography scope").selectOption("page");
  assert.equal(await page.getByLabel("Key value", { exact: true }).count(), 0);
  await page.getByLabel("Choreography scope").selectOption(action.clockId);
  await page.getByLabel(keyLabel, { exact: true }).click();
  const baseTrack = (await doc()).tracks.find(t => t.entityId === copy.id && t.property === "translateY");
  await page.getByRole("button", { name: "Mobile", exact: true }).click();
  await page.getByLabel("Key value", { exact: true }).fill("42");
  await page.getByLabel("Key value", { exact: true }).blur();
  assert.deepEqual((await doc()).tracks.find(t => t.id === baseTrack.id), baseTrack);
  assert((await doc()).tracks.some(t => t.entityId === copy.id && t.property === "translateY" && t.profileId === "mobile" && t.keys.some(k => k.value === 42)));
  await page.getByLabel("Undo", { exact: true }).click();
  await page.getByRole("button", { name: "Desktop", exact: true }).click();
  check("Timeline key editing respects clock scope and forks mobile tracks without changing base");
  await page.screenshot({ path: "test-results/section-choreography.png" });
  check("Collapsible choreography, undoable legacy section conversion and scroll-driven Reveal action");
  await page.evaluate(async () => (await import("/src/store.ts")).studio.save());
  const other = await page.context().newPage();
  await other.goto("http://127.0.0.1:5173"); await other.waitForLoadState("networkidle");
  const originalName = (await doc()).name;
  await page.evaluate(async () => { const { studio } = await import("/src/store.ts"); studio.execute({ type: "document-name", name: "Winning tab" }); await studio.save(); });
  await other.evaluate(async () => { const { studio } = await import("/src/store.ts"); studio.execute({ type: "document-name", name: "Unsynced other tab" }); await studio.save(); });
  assert.equal(await other.evaluate(async () => (await import("/src/store.ts")).studio.get().status), "Recovery copy saved");
  assert(await page.evaluate(async () => (await import("/src/recovery.ts")).readRecoveries().some(c => c.workspace.document.name === "Unsynced other tab")));
  assert.equal(await page.evaluate(async () => (await (await fetch("/api/workspace")).json()).workspace.document.name), "Winning tab");
  await other.close();
  await page.evaluate(async name => { const { studio } = await import("/src/store.ts"); studio.execute({ type: "document-name", name }); await studio.save(); }, originalName);
  check("Two real editor tabs preserve losing edits without overwriting the saved winner");
  // Leave the exported fixture at the start; runtime scroll must drive it independently.
  await page.getByLabel("Return to start", { exact: true }).click();
  await page.getByRole("button", { name: "Compose", exact: true }).click();
};
exports.runtime = async ({ runtime, check }) => {
  const sections = runtime.locator(".page-section"); assert.equal(await sections.count(), 2);
  const id = await runtime.evaluate(async () => { const d = await (await fetch("./composition.json")).json(); return d.actions.at(-1).entityIds[0]; });
  const target = runtime.locator(`[data-entity="${id}"]`);
  await runtime.evaluate(() => scrollTo(0, 0));
  await runtime.waitForFunction(id => Number(getComputedStyle(document.querySelector(`[data-entity="${id}"]`)).opacity) === 0, id);
  const distance = await runtime.evaluate(() => innerHeight * 2 * .125);
  await runtime.evaluate(y => scrollTo(0, y), distance);
  await runtime.waitForFunction(id => Math.abs(Number(getComputedStyle(document.querySelector(`[data-entity="${id}"]`)).opacity) - .5) < .02, id);
  assert(Math.abs((await runtime.locator(".section-viewport").first().boundingBox()).y) < 2);
  await runtime.evaluate(() => scrollTo(0, innerHeight * .5));
  await runtime.waitForFunction(id => Number(getComputedStyle(document.querySelector(`[data-entity="${id}"]`)).opacity) === 1, id);
  await runtime.screenshot({ path: "test-results/runtime-scroll.png" });
  await runtime.setViewportSize({ width: 390, height: 844 });
  await runtime.evaluate(() => scrollTo(0, innerHeight * .25));
  await runtime.waitForFunction(id => Math.abs(Number(getComputedStyle(document.querySelector(`[data-entity="${id}"]`)).opacity) - .5) < .02, id);
  assert(Math.abs((await runtime.locator(".section-viewport").first().boundingBox()).y) < 2);
  await runtime.screenshot({ path: "test-results/runtime-mobile-scroll.png" });
  check("Exported section scroll matches editor progress, pins correctly and adapts to mobile viewport");
};
